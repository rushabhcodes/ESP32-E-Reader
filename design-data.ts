/** Static electrical, placement, and sourcing data for the Rev. B board. */

export type SectionName =
	| "battery_usb"
	| "mcu_power"
	| "display_power"
	| "storage"
	| "controls";

export type PcbPlacement = {
	pcbX: number;
	pcbY: number;
	pcbRotation?: number;
	layer?: "top" | "bottom";
};

export type PassiveSpec = PcbPlacement & {
	name: string;
	value: string;
	footprint: string;
	section: SectionName;
};

export type ChipSpec = PcbPlacement & {
	name: string;
	value: string;
	footprint: string;
	pins: readonly string[];
	noConnect?: readonly string[];
	section: SectionName;
	kind?: "chip" | "connector" | "pushbutton";
};

